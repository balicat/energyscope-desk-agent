CAVEAT_BOTH: set[str] = set()


def answer(names: list[str], summary: str) -> DeskAnswer:
    body = {"facts": [], "spreads": [], "readings": [], "summary": summary}
    for n in names:
        if n in FACTS:
            body["facts"].append(FACTS[n])
            continue
        for part in ("facts", "spreads", "readings"):
            body[part] += G[n].get(part, [])
    a = DeskAnswer(**body)
    a.summary = metrics.tidy(a.summary)
    return a


def problems(names: list[str], summary: str) -> list[str]:
    a = answer(names, summary)
    return metrics.untraceable_numbers(a) + metrics.direction_problems(a)


def caveat_kept(names: list[str], sentence: str) -> bool:
    """Is `sentence`, written as a model caveat beside the recorded answer's own summary, kept by clean_caveats?"""
    first = next((n for n in names if n in G), None)
    a = answer(names, G[first]["summary"] if first else "")
    a.caveats = [sentence]
    return prose.clean_caveats(a) == [sentence]


